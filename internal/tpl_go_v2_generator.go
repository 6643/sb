func (g *GoV2Generator) v2BitmapListCallbacks(t TplType) (string, [4]string) {
	elemType := g.base.getGoType(TplType{Name: t.Name, Kind: t.Kind, IsList: false})
	switch t.Kind {
	case TplKindEnum:
		enumName := PascalCase(t.Name)
		return fmt.Sprintf("func() %s { return %s() }", elemType, g.v2EnumDefaultName(enumName)), [4]string{
			fmt.Sprintf("func(item %s) bool { return %s(item) }", elemType, g.v2EnumIsDefaultName(enumName)),
			fmt.Sprintf("func(item %s) (int, error) { if !%s(item) { return 0, fmt.Errorf(\"非法枚举值: %%d\", item) }; return 1, nil }", elemType, g.v2EnumIsAssignableName(enumName)),
			fmt.Sprintf("func(buf *bytes.Buffer) (%s, error) { value, err := rt.GetU8(buf); if err != nil { return 0, err }; item := %s(value); if !Is%s(item) { return 0, fmt.Errorf(\"非法枚举值: %%d\", item) }; return item, nil }", elemType, elemType, enumName),
			fmt.Sprintf("func(buf *bytes.Buffer, item %s) error { if !Is%s(item) { return fmt.Errorf(\"非法枚举值: %%d\", item) }; return rt.SetU8(buf, uint8(item)) }", elemType, enumName),
		}
	case TplKindStruct:
		typeName := PascalCase(t.Name)
		return "nil", [4]string{
			fmt.Sprintf("func(item %s) bool { return %s(item) }", elemType, g.v2StructIsZeroName(typeName)),
			fmt.Sprintf("func(item %s) (int, error) { return %s(item) }", elemType, g.v2StructSizeName(t.Name)),
			fmt.Sprintf("func(buf *bytes.Buffer) (%s, error) { return %s(buf) }", elemType, g.v2StructReadName(t.Name)),
			fmt.Sprintf("func(buf *bytes.Buffer, item %s) error { return %s(buf, item) }", elemType, g.v2StructSetName(t.Name)),
		}
	default:
		defaultValue := g.base.getGoValue(t.Name)
		_, getter := g.v2PrimitiveGetter(t.Name)
		setter := g.v2PrimitiveSetter(t.Name)
		width, _ := goBaseEncodedWidth(t.Name)
		if t.Name == "f32" || t.Name == "f64" {
			defaultValue = "0"
		}
		return fmt.Sprintf("func() %s { return %s }", elemType, defaultValue), [4]string{
			fmt.Sprintf("func(item %s) bool { return item == 0 }", elemType),
			fmt.Sprintf("func(item %s) (int, error) { return %d, nil }", elemType, width),
			fmt.Sprintf("func(buf *bytes.Buffer) (%s, error) { return rt.%s(buf) }", elemType, getter),
			fmt.Sprintf("func(buf *bytes.Buffer, item %s) error { return rt.%s(buf, item) }", elemType, setter),
		}
	}
}

